const L: Record<string, string[]> = {};
for (const k of Object.keys(G)) L[k] = G[k]!.split("/");

const norm = (t: string): string | null => {
  const up = t.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase();
  let out = "";
  for (const ch of up) {
    if (ch === "Đ" || ch === "Ð") {
      out += "D";
      continue;
    }
    if (ch === "\t" || ch === "\n") {
      if (out && !out.endsWith(" ")) out += " ";
      continue;
    }
    if (ch === "’" || ch === "‘" || ch === "`") {
      out += "'";
      continue;
    }
    if (ch === "—" || ch === "–" || ch === "−") {
      out += "-";
      continue;
    }
    if (ch === "…") {
      out += "...";
      continue;
    }
    if (!L[ch]) return null;
    out += ch;
  }
  out = out.trim();
  return out || null;
};

const SCL: [number, number][] = [
  [6, 3],
  [4, 2],
  [2, 1],
];

const gpOf = (sc: number): number => (sc >= 4 ? sc : 1);

const wid = (sc: number, n: number): number => (5 * sc + gpOf(sc)) * n - gpOf(sc);

export const bigTxt = (t: string, maxW: number, maxH: number, fre = false): string[] | null => {
  const c = norm(t);
  if (!c) return null;
  const anchor = fre ? c.length : 7;
  let pick: [number, number] = [2, 1];
  for (const [sc, yr] of SCL) {
    if (wid(sc, anchor) <= maxW && 7 * yr <= maxH) {
      pick = [sc, yr];
      break;
    }
  }
  const [sc, yr] = pick;
  const n = c.length;
  if (7 * yr > maxH) return null;
  let pxw = sc;
  let gp = gpOf(sc);
  if (wid(pxw, n) > maxW) {
    pxw = 0;
    for (let p = sc - 1; p >= 1; p--) {
      if (wid(p, n) <= maxW) {
        pxw = p;
        break;
      }
    }
    if (pxw) gp = gpOf(pxw);
    else if (5 * n <= maxW) {
      pxw = 1;
      gp = 0;
    } else return null;
  }
  const out: string[] = [];
  for (let pr = 0; pr < 7; pr++) {
    let row = "";
    for (let ci = 0; ci < c.length; ci++) {
      const g = L[c[ci]!]!;
      for (let pc = 0; pc < 5; pc++) row += g[pr]![pc] === "#" ? "█".repeat(pxw) : " ".repeat(pxw);
      if (ci < c.length - 1) row += " ".repeat(gp);
    }
    for (let y = 0; y < yr; y++) out.push(row);
  }
  while (out.length && !out[0]!.trim()) out.shift();
  while (out.length && !out[out.length - 1]!.trim()) out.pop();
  if (!out.length) return null;
  const wd = out[0]!.length;
  let cl = 0;
  let cr = wd - 1;
  while (cl <= cr && out.every((r) => r[cl] === " ")) cl++;
  while (cr >= cl && out.every((r) => r[cr] === " ")) cr--;
  if (cl > 0 || cr < wd - 1) {
    for (let i = 0; i < out.length; i++) out[i] = out[i]!.slice(cl, cr + 1);
  }
  return out;
};
